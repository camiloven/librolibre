// Helper to get today's date formatted in ISO with hour and minute
function getTodayIso(hours: number, minutes: number, dayOffset = 0): string {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  d.setHours(hours, minutes, 0, 0);
  return d.toISOString();
}

